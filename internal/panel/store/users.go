// SeenDevice records a device fetching a subscription and enforces the limit.
//
// A device already on the list is just touched. A new one is refused when the
// user is at their limit, which is the whole point of the ledger: the limit is
// on distinct devices, not on concurrent connections, so it is enforced where
// the device identifies itself.
func (s *Store) SeenDevice(ctx context.Context, userID uint64, hwid, model, platform, appVersion, ip string) (*Device, error) {
	if hwid == "" {
		return nil, errors.New("store: no device id given")
	}
	var deviceID uint64
	err := s.Tx(ctx, func(tx *sqlx.Tx) error {
		var existing Device
		err := tx.GetContext(ctx, &existing,
			`SELECT id, user_id, hwid, model, platform, app_version, first_seen_at, last_seen_at, last_ip
			 FROM user_devices WHERE user_id = ? AND hwid = ?`, userID, hwid)
		switch {
		case err == nil:
			deviceID = existing.ID
			if _, err := tx.ExecContext(ctx,
				`UPDATE user_devices SET last_seen_at = ?, last_ip = ?, model = ?, platform = ?, app_version = ?
				 WHERE id = ?`,
				time.Now().UTC(), nullString(ip), nullString(model), nullString(platform),
				nullString(appVersion), existing.ID); err != nil {
				return fmt.Errorf("store: touch device: %w", err)
			}
			return nil

		case errors.Is(err, sql.ErrNoRows):
			// A new device: check the limit under the same transaction, so two
			// phones registering at once cannot both slip past it.
			var limit uint32
			if err := tx.GetContext(ctx, &limit,
				`SELECT devices_limit FROM users WHERE id = ? FOR UPDATE`, userID); err != nil {
				return fmt.Errorf("store: user %d device limit: %w", userID, err)
			}
			if limit > 0 {
				var count uint32
				if err := tx.GetContext(ctx, &count,
					`SELECT COUNT(*) FROM user_devices WHERE user_id = ?`, userID); err != nil {
					return fmt.Errorf("store: count devices: %w", err)
				}
				if count >= limit {
					return ErrDeviceLimit
				}
			}
			res, err := tx.ExecContext(ctx,
				`INSERT INTO user_devices (user_id, hwid, model, platform, app_version, last_ip)
				 VALUES (?, ?, ?, ?, ?, ?)`,
				userID, hwid, nullString(model), nullString(platform), nullString(appVersion), nullString(ip))
			if err != nil {
				return fmt.Errorf("store: add device: %w", err)
			}
			lastID, _ := res.LastInsertId()
			deviceID = uint64(lastID)
			return nil

		default:
			return fmt.Errorf("store: read device: %w", err)
		}
	})
	if err != nil {
		return nil, err
	}

	var device Device
	if err := s.DB.GetContext(ctx, &device,
		`SELECT id, user_id, hwid, model, platform, app_version, first_seen_at, last_seen_at, last_ip
		 FROM user_devices WHERE id = ?`, deviceID); err != nil {
		return nil, fmt.Errorf("store: read device %d: %w", deviceID, err)
	}
	return &device, nil
}

// UserDevices lists a user's devices, most recently seen first.
func (s *Store) UserDevices(ctx context.Context, userID uint64) ([]Device, error) {
	var out []Device
	if err := s.DB.SelectContext(ctx, &out,
		`SELECT id, user_id, hwid, model, platform, app_version, first_seen_at, last_seen_at, last_ip
		 FROM user_devices WHERE user_id = ? ORDER BY last_seen_at DESC`, userID); err != nil {
		return nil, fmt.Errorf("store: user %d devices: %w", userID, err)
	}
	return out, nil
}

// DeleteDevice removes one device, freeing a slot.
func (s *Store) DeleteDevice(ctx context.Context, userID, deviceID uint64) error {
	res, err := s.DB.ExecContext(ctx,
		`DELETE FROM user_devices WHERE id = ? AND user_id = ?`, deviceID, userID)
	if err != nil {
		return fmt.Errorf("store: delete device %d: %w", deviceID, err)
	}
	if affected, _ := res.RowsAffected(); affected == 0 {
		return fmt.Errorf("store: device %d: %w", deviceID, ErrNotFound)
	}
	return nil
}

// MarkSubFetched records that the app fetched a subscription, so the panel can
// show which users are actually using theirs.
func (s *Store) MarkSubFetched(ctx context.Context, userID uint64) error {
	if _, err := s.DB.ExecContext(ctx,
		`UPDATE users SET last_sub_fetch_at = ? WHERE id = ?`, time.Now().UTC(), userID); err != nil {
		return fmt.Errorf("store: mark subscription fetched: %w", err)
	}
	return nil
}

// prefixColumns qualifies a column list with a table alias, so a joined query
// can reuse the same list as a plain one.
func prefixColumns(columns, alias string) string {
	parts := strings.Split(columns, ",")
	for i, part := range parts {
		parts[i] = alias + "." + strings.TrimSpace(part)
	}
	return strings.Join(parts, ", ")
}

func timeOrNull(t *time.Time) any {
	if t == nil {
		return nil
	}
	return t.UTC()
}
